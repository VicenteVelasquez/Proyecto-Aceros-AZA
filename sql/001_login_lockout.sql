  ADD COLUMN IF NOT EXISTS bloqueado_hasta timestamptz NULL,
  ADD COLUMN IF NOT EXISTS ultimo_intento_fallido timestamptz NULL;
CREATE TABLE IF NOT EXISTS public.auditoria_desbloqueos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id integer NOT NULL,
  usuario_id integer NOT NULL,
  rol_actor text NOT NULL,
  fecha timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ficha_personal_bloqueado_hasta
  ON public.ficha_personal (bloqueado_hasta)
  WHERE bloqueado_hasta IS NOT NULL;
